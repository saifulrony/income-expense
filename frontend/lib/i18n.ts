export function translateCategory(name: string, lang?: AppLanguage): string {
  if (!name) return name;
  const currentLang = lang || getAppLanguage();
  if (currentLang === 'en') return name;
  const mapped = DEFAULT_CATEGORY_TRANSLATIONS[name];
  if (mapped && mapped[currentLang]) {
    return mapped[currentLang];
  }
  return name;
}

export function useTranslateCategory(): (name: string) => string {
  const { lang } = useTranslation();
  return (name: string) => translateCategory(name, lang);
}

export function getAppLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem(LANG_KEY) as AppLanguage | null;
  if (saved && saved in TRANSLATIONS) return saved;
  return 'en';
}

export function setAppLanguage(lang: AppLanguage): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  window.dispatchEvent(new CustomEvent(APP_LANGUAGE_EVENT, { detail: lang }));
}

export function translate(key: string, lang?: AppLanguage): string {
  const activeLang = lang || getAppLanguage();
  return TRANSLATIONS[activeLang]?.[key] || TRANSLATIONS.en[key] || key;
}

export function useTranslation() {
  const [lang, setLangState] = useState<AppLanguage>(() => getAppLanguage());

  useEffect(() => {
    const current = getAppLanguage();
    setLangState(current);
    document.documentElement.setAttribute('lang', current);
    document.documentElement.setAttribute('dir', current === 'ar' ? 'rtl' : 'ltr');

    const handleLangChange = (e: Event) => {
      const detail = (e as CustomEvent).detail as AppLanguage | undefined;
      const next = detail || getAppLanguage();
      setLangState(next);
      document.documentElement.setAttribute('lang', next);
      document.documentElement.setAttribute('dir', next === 'ar' ? 'rtl' : 'ltr');
    };
    window.addEventListener(APP_LANGUAGE_EVENT, handleLangChange);
    window.addEventListener('storage', handleLangChange);
    return () => {
      window.removeEventListener(APP_LANGUAGE_EVENT, handleLangChange);
      window.removeEventListener('storage', handleLangChange);
    };
  }, []);

  const t = (key: string): string => {
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
  };

  return { lang, setLang: setAppLanguage, t };
}

